export function ProviderLogoIcon({ providerId, size = 20, className }: { providerId: string; size?: number; className?: string }) {
  const id = providerId.toLowerCase();
  if (id === "chatgpt") {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" className={className} aria-hidden="true">
        <path d="M12 2a10 10 0 1 0 10 10A10 10 0 0 0 12 2zm0 14a4 4 0 1 1 4-4 4 4 0 0 1-4 4z" />
      </svg>
    );
  }
  if (id === "gemini") {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" className={className} aria-hidden="true">
        <path d="M12 2L9 9l-7 3 7 3 3 7 3-7 7-3-7-3z" />
      </svg>
    );
  }
  if (id === "deepseek") {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" className={className} aria-hidden="true">
        <circle cx="12" cy="12" r="9" />
        <path d="M12 7v10M8 12h8" />
      </svg>
    );
  }
  // Fallback letter avatar for other providers
  const letter = id.charAt(0).toUpperCase();
  return (
    <div
      style={{
        width: size,
        height: size,
        borderRadius: "4px",
        background: "var(--bg-input)",
        border: "1px solid var(--border-color-card)",
        color: "var(--accent)",
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        fontSize: Math.floor(size * 0.6),
        fontWeight: 700,
        textTransform: "uppercase",
        flexShrink: 0,
      }}
      aria-hidden="true"
    >
      {letter}
    </div>
  );
}
